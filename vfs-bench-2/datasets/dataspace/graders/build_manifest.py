"""Pin DataSpace inputs and generate its Monty-compatible evaluator.

Run after datasets/dataspace/fetch.py; --check refuses drift or an edited port.
The relation/number functions remain verbatim; CSV/date adapters are separate.
"""
import argparse
import ast
import hashlib
import json
import runpy
from pathlib import Path

DIRECTORY = Path(__file__).resolve().parent
DATASET = DIRECTORY.parent
ROOT = DATASET.parents[1]
STATE = ROOT / 'state/dataspace'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def program():
    source = (DIRECTORY / 'reference/evaluate.py').read_text()
    parts = [
        '# Generated by graders/build_manifest.py; '
        'edit the adapter, not this file.'
    ]
    omit = {
        'parse_iso_datetime', 'normalize_date', 'normalize_datetime',
        'read_strict_csv', 'natural_task_key', 'load_configs',
        'hash_config_set', 'discover_unscored_prediction_tasks',
        'evaluate_suite', 'parse_args', 'main'
    }
    exceptions = {
        'EvaluationFatalError': 'RuntimeError',
        'PredictionFormatError': 'ValueError',
        'CellNormalizationError': 'TypeError'
    }
    for node in ast.parse(source).body:
        if isinstance(node, ast.If):
            continue
        if isinstance(node,
                      ast.Import) and node.names[0].name in ('argparse', 'csv',
                                                             'hashlib', 'sys'):
            continue
        if isinstance(node, ast.ImportFrom) and node.module == '__future__':
            continue
        if isinstance(node, ast.FunctionDef) and node.name in omit:
            continue
        if isinstance(node, ast.ClassDef) and node.name in exceptions:
            parts.append(f'{node.name} = {exceptions[node.name]}')
            continue
        start = node.lineno
        if isinstance(node, ast.ClassDef) and node.decorator_list:
            start = node.decorator_list[0].lineno
        text = '\n'.join(source.splitlines()[start - 1:node.end_lineno])
        text = text.replace('from typing import Any, Hashable',
                            'from typing import Any')
        text = text.replace('path.read_text(encoding="utf-8")',
                            'path.read_bytes().decode("utf-8")')
        text = text.replace('CanonicalCell = Hashable', 'CanonicalCell = Any')
        text = text.replace('@dataclass(frozen=True, slots=True)',
                            '@dataclass(frozen=True)')
        text = text.replace('if not prediction_path.exists():',
                            'if not prediction_exists(prediction_path):')
        parts.append(text)
    return '\n\n'.join(parts) + '\n'


def manifest():
    source = (STATE / 'evaluation/evaluate.py').read_bytes()
    assert source == (DIRECTORY / 'reference/evaluate.py').read_bytes()
    tasks = {}
    for slug, task_id in runpy.run_path(str(DATASET /
                                            'generate.py'))['TASKS'].items():
        tasks[slug] = {
            'runtime':
            'dataspace-monty',
            'task_id':
            task_id,
            'config_sha256':
            digest(
                (STATE /
                 f'benchmark/evaluation/configs/{task_id}.json').read_bytes()),
            'gold_sha256':
            digest(
                (STATE / f'benchmark/output/{task_id}/gold.csv').read_bytes()),
        }
    return {
        'upstream_commit': '6491caa4c70cc06cacb6103ba73cefb00746abfe',
        'dataset_revision': '96be19257d7aa251dbce4771d46a26fc36f6dc52',
        'reference_sha256': digest(source),
        'port_sha256': digest(program().encode()),
        'tasks': tasks
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--check-port', action='store_true')
    args = parser.parse_args()
    if args.check_port:
        data = json.loads((DIRECTORY / 'manifest.json').read_text())
        assert (DIRECTORY / 'port.py').read_text() == program()
        assert digest(program().encode()) == data['port_sha256']
        assert digest(
            (DIRECTORY /
             'reference/evaluate.py').read_bytes()) == data['reference_sha256']
        print('Pinned DataSpace source and generated port verified')
        raise SystemExit(0)
    for name, text in {
            'port.py': program(),
            'manifest.json': json.dumps(manifest(), indent=2) + '\n'
    }.items():
        path = DIRECTORY / name
        if args.check:
            assert path.read_text() == text, f'DataSpace drift: {name}'
        else:
            path.write_text(text)
    print('46 DataSpace reference definitions verified')
