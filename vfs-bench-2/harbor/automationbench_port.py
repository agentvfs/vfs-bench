"""Generate Monty code from the pinned rubric and schema (stdlib only).

Models become tagged records. Attribute access and method dispatch are
adapted mechanically; assertion expressions and scoring control flow are
preserved. Module globals are namespaced to retain Python import semantics.
"""
import ast
import copy
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIRECTORY = HERE / "graders/automationbench"
REFERENCE = DIRECTORY / "reference/automationbench"


def symbol(name):
    return "ab_" + name.replace(".", "__")


class Generator:

    def __init__(self):
        self.modules = {}
        self.names = {}
        self.classes = {}
        for path in sorted(REFERENCE.rglob("*.py")):
            module = str(path.relative_to(REFERENCE).with_suffix("")).replace(
                "/", ".")
            module = module.removesuffix(".__init__")
            tree = ast.parse(path.read_text())
            self.modules[module] = tree
            names = {}
            for node in tree.body:
                if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                    names[node.name] = module + "." + node.name
                    if isinstance(node, ast.ClassDef):
                        self.classes[module + "." + node.name] = (module, node)
                elif isinstance(node, ast.ImportFrom):
                    if (node.module or "").startswith("automationbench."):
                        prefix = node.module.removeprefix("automationbench.")
                        for alias in node.names:
                            names[alias.asname
                                  or alias.name] = prefix + "." + alias.name
                elif isinstance(node, (ast.Assign, ast.AnnAssign)):
                    targets = node.targets if isinstance(
                        node, ast.Assign) else [node.target]
                    for target in targets:
                        if isinstance(target, ast.Name):
                            names[target.id] = module + "." + target.id
            self.names[module] = names
            for node in ast.walk(tree):
                if isinstance(node, ast.ImportFrom) and (
                        node.module or "").startswith("automationbench."):
                    for alias in node.names:
                        names[alias.asname
                              or alias.name] = node.module.removeprefix(
                                  "automationbench.") + "." + alias.name
        self.method_names = {
            n.name
            for _, cls in self.classes.values()
            for n in cls.body if isinstance(n, ast.FunctionDef)
        } | {"model_dump"}

    def resolve(self, name):
        module, _, local = name.rpartition(".")
        target = self.names.get(module, {}).get(local, name)
        return self.resolve(target) if target != name else name

    def methods(self, key):
        module, cls = self.classes["schema." + key]
        methods = {}
        for base in cls.bases:
            if isinstance(base, ast.Name):
                parent = self.resolve(self.names[module].get(base.id, base.id))
                if parent in self.classes:
                    methods.update(self.methods(
                        parent.removeprefix("schema.")))
        for node in cls.body:
            if isinstance(node, ast.FunctionDef):
                methods[node.name] = (module, node)
        return methods

    def field_options(self, key):
        module, cls = self.classes["schema." + key]
        options = {"populate_by_name": False, "validation_aliases": {}}
        for base in cls.bases:
            if isinstance(base, ast.Name):
                parent = self.resolve(self.names[module].get(base.id, base.id))
                if parent in self.classes:
                    options = self.field_options(
                        parent.removeprefix("schema."))
        for node in cls.body:
            if isinstance(node, ast.Assign) and ast.unparse(
                    node.targets[0]) == "model_config":
                config = ({
                    k.arg: ast.literal_eval(k.value)
                    for k in node.value.keywords
                } if isinstance(node.value, ast.Call) else ast.literal_eval(
                    node.value))
                if "populate_by_name" in config:
                    options["populate_by_name"] = config["populate_by_name"]
            if isinstance(node, ast.AnnAssign) and isinstance(
                    node.value, ast.Call):
                for keyword in node.value.keywords:
                    if keyword.arg == "validation_alias":
                        options["validation_aliases"][
                            node.target.id] = ast.literal_eval(keyword.value)
        return options

    def generate(self, models):
        parts = [
            "# Generated by automationbench_port.py; do not edit.\n"
            "# Derived from AutomationBench (c) 2026 Zapier, Inc.\n"
            "# SPDX-License-Identifier: MIT; see reference/LICENSE.\n"
        ]
        handlers = {}
        methods = {}
        properties = {}
        validators = {}
        factories = {}
        initializers = {}
        posts = {}
        # Only grading/read helpers and validators are needed.
        needed = set()
        for module, tree in self.modules.items():
            if module.startswith("rubric.assertions"):
                needed.update(n.func.attr for n in ast.walk(tree)
                              if isinstance(n, ast.Call)
                              and isinstance(n.func, ast.Attribute))
        needed.add("_was_row_updated")
        # Methods can call other model helpers.
        changed = True
        while changed:
            before = len(needed)
            for key in models:
                for name, (_, node) in self.methods(key).items():
                    if name in needed:
                        needed.update(n.func.attr for n in ast.walk(node)
                                      if isinstance(n, ast.Call)
                                      and isinstance(n.func, ast.Attribute))
            changed = before != len(needed)
        for key, desc in models.items():
            methods[key] = {}
            properties[key] = {}
            validators[key] = {}
            for name, (module, original) in self.methods(key).items():
                decorators = [ast.unparse(d) for d in original.decorator_list]
                validator = name in desc["before"] or name in desc[
                    "field_validators"]
                prop = "property" in decorators
                if not (name in needed or validator or prop
                        or name in ("__init__", "model_post_init")):
                    continue
                node = copy.deepcopy(original)
                node.decorator_list = []
                node.name = symbol("schema." + key + "." + name)
                if name == "__init__":
                    node.args.kwarg = None
                    node.args.args.append(ast.arg(arg="data"))
                if "staticmethod" in decorators:
                    node.args.args.insert(0, ast.arg(arg="_unused"))
                transformed = Transform(self, module).visit(node)
                parts.append(
                    ast.unparse(ast.fix_missing_locations(transformed)))
                if validator:
                    validators[key][name] = node.name
                elif prop:
                    properties[key][name] = node.name
                elif name == "__init__":
                    initializers[key] = node.name
                elif name == "model_post_init":
                    posts[key] = node.name
                else:
                    methods[key][name] = node.name
            for field in desc["fields"]:
                factory = field.get("factory", "")
                if factory.startswith("lambda:"):
                    expr = ast.parse(field["source"])
                    lambdas = [
                        n for n in ast.walk(expr) if isinstance(n, ast.Lambda)
                    ]
                    assert len(lambdas) == 1, factory
                    module = "schema." + key.rpartition(".")[0]
                    factories[factory] = ast.unparse(
                        Transform(self, module).visit(lambdas[0]))
                elif factory.startswith("schema."):
                    factories[factory] = symbol(factory)
        # Preserve all 597 registered handlers, including loop-generated ones.
        for module, tree in self.modules.items():
            if module in ("rubric.registry", "__init__"):
                continue
            originals = list(tree.body)
            # Upstream generates 26 operations-app handlers in one loop.
            if module == "rubric.assertions.ops_apps":
                apps = ast.literal_eval(
                    next(n.value for n in tree.body
                         if isinstance(n, ast.Assign)
                         and ast.unparse(n.targets[0]) == "APP_ATTRS"))
                loop = next(n for n in tree.body if isinstance(n, ast.For))
                for app, attr in apps.items():
                    for original in loop.body:
                        if not isinstance(original, ast.FunctionDef):
                            continue
                        fn = copy.deepcopy(original)
                        assertion = app + ("_action_exists" if fn.name ==
                                           "_exists" else "_action_not_exists")
                        fn.name = assertion
                        fn.args.defaults = [
                            ast.Constant(attr),
                            ast.Constant(app)
                        ]
                        fn.decorator_list = [
                            ast.Call(
                                ast.Attribute(
                                    ast.Name("AssertionRegistry", ast.Load()),
                                    "register", ast.Load()),
                                [ast.Constant(assertion)], [])
                        ]
                        originals.append(fn)
            for original in originals:
                if isinstance(original, ast.FunctionDef):
                    if (module == "rubric"
                            and original.name != "partial_credit"):
                        continue
                    if (module == "tools.api.impl.google_sheets"
                            and original.name != "_was_row_updated"):
                        continue
                    node = copy.deepcopy(original)
                    for decorator in node.decorator_list:
                        if isinstance(decorator, ast.Call) and ast.unparse(
                                decorator.func
                        ) == "AssertionRegistry.register":
                            handlers[ast.literal_eval(
                                decorator.args[0])] = symbol(module + "." +
                                                             node.name)
                    node.decorator_list = []
                    node.name = symbol(module + "." + node.name)
                    transformed = Transform(self, module).visit(node)
                    parts.append(
                        ast.unparse(ast.fix_missing_locations(transformed)))
                elif isinstance(original, (ast.Assign, ast.AnnAssign)):
                    # Module constants used by handlers/helpers. Model classes
                    # and Pydantic rebuild calls never enter the Monty program.
                    transformed = Transform(self, module).visit(
                        copy.deepcopy(original))
                    parts.append(
                        ast.unparse(ast.fix_missing_locations(transformed)))

        def table(name, values):
            return name + " = {\n" + ",\n".join(
                repr(k) + ": " + v for k, v in values.items()) + "\n}"

        def nested(name, values):
            return table(
                name, {
                    k:
                    "{" + ", ".join(repr(n) + ": " + f
                                    for n, f in v.items()) + "}"
                    for k, v in values.items()
                })

        parts += [
            table("HANDLERS", handlers),
            nested("METHODS", methods),
            nested("PROPERTIES", properties),
            nested("VALIDATORS", validators),
            table("FACTORIES", factories),
            table("INITIALIZERS", initializers),
            table("POST_INIT", posts)
        ]
        parts.append("FIELD_OPTIONS = " +
                     repr({k: self.field_options(k)
                           for k in models}))
        assert len(handlers) == 597, len(handlers)
        return "\n\n".join(parts) + "\n"


class Transform(ast.NodeTransformer):

    def __init__(self, generator, module):
        self.generator = generator
        self.module = module
        self.locals = set()

    def visit_FunctionDef(self, node):
        previous = self.locals
        self.locals = previous | {
            n.id
            for n in ast.walk(node)
            if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store)
        }
        self.locals.update(n.arg for n in ast.walk(node)
                           if isinstance(n, ast.arg))
        self.locals.update(n.name for n in ast.walk(node)
                           if isinstance(n, ast.FunctionDef) and n is not node)
        node.returns = None
        node.type_comment = None
        node = self.generic_visit(node)
        self.locals = previous
        return node

    def visit_arg(self, node):
        node.annotation = None
        return node

    def visit_AnnAssign(self, node):
        if node.value is None:
            return None
        return self.visit(ast.Assign(targets=[node.target], value=node.value))

    def visit_Name(self, node):
        if node.id in self.locals:
            return node
        name = self.generator.resolve(
            self.generator.names.get(self.module, {}).get(node.id, node.id))
        if name in self.generator.classes and name.startswith("schema."):
            return ast.copy_location(
                ast.Constant(name.removeprefix("schema.")), node)
        special = {
            "getattr": "model_get",
            "hasattr": "model_has",
            "setattr": "model_set",
            "unquote": "url_unquote",
            "uuid4": "new_uuid"
        }
        return ast.copy_location(
            ast.Name(id=special.get(name,
                                    symbol(name) if "." in name else name),
                     ctx=node.ctx), node)

    def visit_Assign(self, node):
        if len(node.targets) == 1 and isinstance(node.targets[0],
                                                 ast.Attribute):
            target = node.targets[0]
            return ast.Expr(
                ast.Call(ast.Name("model_set", ast.Load()), [
                    self.visit(target.value),
                    ast.Constant(target.attr),
                    self.visit(node.value)
                ], []))
        return self.generic_visit(node)

    def visit_Delete(self, node):
        result = []
        for target in node.targets:
            assert isinstance(target, ast.Subscript), ast.unparse(node)
            result.append(
                ast.Expr(
                    ast.Call(
                        ast.Attribute(self.visit(target.value), "pop",
                                      ast.Load()), [self.visit(target.slice)],
                        [])))
        return result

    def visit_Attribute(self, node):
        # Standard-library attributes keep their native Monty implementations.
        root = node
        while isinstance(root, ast.Attribute):
            root = root.value
        if isinstance(root, ast.Name) and root.id in {
                "re", "datetime", "date", "timezone", "random", "string",
                "hashlib", "time", "uuid", "urllib"
        }:
            if root.id == "string":
                import string
                return ast.Constant(getattr(string, node.attr))
            if ast.unparse(node) == "uuid.uuid4":
                return ast.Name("new_uuid", ast.Load())
            if ast.unparse(node) == "urllib.parse.unquote":
                return ast.Name("url_unquote", ast.Load())
            return node
        if ast.unparse(node) == "AssertionRegistry.check":
            return ast.Name("check_assertion", ast.Load())
        if ast.unparse(node) == "os.environ":
            return ast.Dict([], [])
        return ast.Call(ast.Name("model_get", ast.Load()),
                        [self.visit(node.value),
                         ast.Constant(node.attr)], [])

    def visit_Call(self, node):
        if ast.unparse(node.func) == "super().__init__":
            return ast.Call(
                ast.Name("populate_model", ast.Load()),
                [ast.Name("self", ast.Load()),
                 ast.Name("data", ast.Load())], [])
        if isinstance(node.func, ast.Name):
            name = self.generator.resolve(
                self.generator.names.get(self.module,
                                         {}).get(node.func.id, node.func.id))
            if name.startswith("schema.") and name in self.generator.classes:
                assert not node.args
                return ast.Call(ast.Name("build_model", ast.Load()), [
                    ast.Constant(name.removeprefix("schema.")),
                    ast.Dict([
                        ast.Constant(k.arg) if k.arg else None
                        for k in node.keywords
                    ], [self.visit(k.value) for k in node.keywords])
                ], [])
        if isinstance(node.func, ast.Attribute):
            transformed = self.visit_Attribute(node.func)
            if isinstance(transformed, ast.Call):
                if node.func.attr in self.generator.method_names:
                    return ast.Call(ast.Name("model_call", ast.Load()), [
                        *transformed.args, *[self.visit(a) for a in node.args]
                    ], [
                        ast.keyword(k.arg, self.visit(k.value))
                        for k in node.keywords
                    ])
                return ast.Call(
                    ast.Attribute(self.visit(node.func.value), node.func.attr,
                                  ast.Load()),
                    [self.visit(a) for a in node.args], [
                        ast.keyword(k.arg, self.visit(k.value))
                        for k in node.keywords
                    ])
        return self.generic_visit(node)

    def visit_Import(self, node):
        return None

    def visit_ImportFrom(self, node):
        return None
